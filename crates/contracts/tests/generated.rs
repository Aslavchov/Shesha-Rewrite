//! Fails when `web/src/generated` is not what the generator would write.
//! Read-only: fixing it is the generator's job.

use contracts::codegen;

#[test]
fn generated_typescript_is_up_to_date() {
    let dir = codegen::output_dir();
    let problems = codegen::stale(&dir, &codegen::render())
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()));

    assert!(
        problems.is_empty(),
        "\n{} is out of date:\n  - {}\nRun `{}` and commit the result.\n",
        dir.display(),
        problems.join("\n  - "),
        codegen::COMMAND,
    );
}

#[test]
fn rendering_is_deterministic() {
    assert_eq!(codegen::render(), codegen::render());
}

#[test]
fn every_file_has_the_header_and_unix_line_endings() {
    for (name, contents) in codegen::render() {
        let first_line = contents.lines().next().unwrap_or_default();
        assert!(
            first_line.starts_with("// Generated by") && first_line.contains(codegen::COMMAND),
            "{name} has no generated-file header"
        );
        assert!(!contents.contains('\r'), "{name} contains CR");
        assert!(contents.ends_with('\n'), "{name} has no final newline");
    }
}

#[test]
fn app_name_is_exported_from_the_rust_constant() {
    let files = codegen::render();
    let expected = format!("export const APP_NAME = \"{}\";", contracts::APP_NAME);
    assert!(files["app.ts"].contains(&expected));
    assert!(files["index.ts"].contains("export { APP_NAME } from \"./app\";"));
}

